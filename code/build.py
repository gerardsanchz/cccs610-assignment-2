"""Rebuild the Word report from assignment-2.md on the course's IEEE template.

The reference document is generated by code/make_reference.py (the IEEE look on
pandoc's own styles; its docstring says why the converted .doc template is not used).
build/ is ignored by git. The upload is a PDF exported by Word from the built .docx;
that PDF goes to submitted/ by hand, byte for byte.

Run from the deliverable folder: uv run --script code/build.py

Every step runs from the deliverable folder, wherever the script is started from, and the
first one that fails ends the build with its exit status.
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent

STEPS = (
    ["uv", "run", "-q", "--with", "python-docx", "python", "code/make_reference.py"],
    [
        "condor-docx",
        "build",
        "assignment-2.md",
        "build.yaml",
        "build/",
        "--grid-tables",
    ],
    [
        "uv",
        "run",
        "-q",
        "--with",
        "python-docx",
        "python",
        "code/free_table_tails.py",
        "build/assignment-2.docx",
    ],
)


def main() -> int:
    os.chdir(HERE)
    try:
        Path("build").mkdir(exist_ok=True)
    except OSError as error:
        print(f"build.py: {error}", file=sys.stderr)
        return 1
    for step in STEPS:
        try:
            status = subprocess.run(step, check=False).returncode
        except FileNotFoundError:
            print(f"build.py: {step[0]}: command not found", file=sys.stderr)
            return 127
        if status != 0:
            return status
    return 0


if __name__ == "__main__":
    sys.exit(main())
